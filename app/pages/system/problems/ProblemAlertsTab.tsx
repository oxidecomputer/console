import { createColumnHelper } from '@tanstack/react-table'

import { api, getListQFn, queryClient, type Alert } from '@oxide/api'
import { Notifications24Icon } from '@oxide/design-system/icons/react'

import { AlertClassBadge } from '~/components/AlertClassBadge'
import { makeCrumb } from '~/hooks/use-crumbs'
import { useProblemSelector } from '~/hooks/use-params'
import { LinkCell } from '~/table/cells/LinkCell'
import { Columns } from '~/table/columns/common'
import { useQueryTable } from '~/table/QueryTable'
import { EmptyMessage } from '~/ui/lib/EmptyMessage'
import { truncate } from '~/ui/lib/Truncate'
import { pb } from '~/util/path-builder'
import type * as PP from '~/util/path-params'

import type { Route } from './+types/ProblemAlertsTab'

const alertList = ({ problemId }: PP.Problem) =>
  getListQFn(api.problemAlertList, {
    path: { problemId },
    query: { sortBy: 'time_and_id_descending' },
  })

export async function clientLoader({ params }: Route.ClientLoaderArgs) {
  const { problemId } = params
  await queryClient.prefetchQuery(alertList({ problemId }).optionsFn())
  return null
}

export const handle = makeCrumb('Alerts')

const colHelper = createColumnHelper<Alert>()
const columns = [
  colHelper.accessor('timeCreated', Columns.timeCreated),
  colHelper.accessor('class', {
    cell: (info) => <AlertClassBadge>{info.getValue()}</AlertClassBadge>,
  }),
  colHelper.accessor('id', {
    header: 'ID',
    cell: (info) => (
      <LinkCell to={pb.alert({ alertId: info.getValue() })}>
        {truncate(info.getValue(), 14, 'middle')}
      </LinkCell>
    ),
  }),
]

export default function ProblemAlertsTab() {
  const selector = useProblemSelector()
  const { table } = useQueryTable({
    query: alertList(selector),
    columns,
    emptyState: (
      <EmptyMessage
        icon={<Notifications24Icon />}
        title="No alerts"
        body="Alerts generated by this problem will appear here"
      />
    ),
  })
  return table
}
